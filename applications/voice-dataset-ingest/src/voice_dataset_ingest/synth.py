"""Deterministic synthetic clips and consent records for tests and demonstrations.

Everything is generated from a fixed seed with the standard library: tones with a slow envelope
stand in for speech, so no recording of a person and no model is involved. The output is a
temporary-directory friendly layout:

    <out>/clips/<clip_id>.wav
    <out>/consents/<consent_id>.json
    <out>/plan.json            what each clip is and what the pipeline is expected to do with it
"""
from __future__ import annotations

import array
import json
import math
import random
from pathlib import Path
from typing import Any

from .audio import write_wav

RATE = 16000
GRANTED_AT = "2026-01-01T00:00:00Z"
PAST = "2020-01-01T00:00:00Z"
FUTURE = "2999-01-01T00:00:00Z"

# speaker -> (consent id, how the consent is configured)
SPEAKERS = {
    "spk_a": ("consent_synth_spk_a", "active"),
    "spk_b": ("consent_synth_spk_b", "revoked"),
    "spk_c": ("consent_synth_spk_c", "expired"),
    "spk_d": ("consent_synth_spk_d", "no_training_use"),
}

# clip id -> (speaker, audio kind, expected outcome)
CLIPS = {
    "utt_0001": ("spk_a", "valid", "accepted"),
    "utt_0002": ("spk_a", "stereo_48k", "accepted"),
    "utt_0003": ("spk_a", "silent", "rejected: silent"),
    "utt_0004": ("spk_a", "clipped", "rejected: clipped"),
    "utt_0005": ("spk_a", "too_short", "rejected: too_short"),
    "utt_0006": ("spk_a", "truncated", "rejected: truncated"),
    "utt_0007": ("spk_a", "not_audio", "rejected: unreadable"),
    "utt_0008": ("spk_b", "valid", "rejected: consent revoked"),
    "utt_0009": ("spk_c", "valid", "rejected: consent expired"),
    "utt_0010": ("spk_d", "valid", "rejected: consent without training use"),
}

TEXTS = [
    "The delivery window opens at nine in the morning.",
    "Please confirm the second address on the form.",
    "Turn left after the bridge and keep going.",
    "The meeting moved to the afternoon.",
]


def tone(rng: random.Random, seconds: float, rate: int = RATE, amplitude: int = 8000) -> array.array:
    """A voiced-sounding tone: two harmonics, a slow envelope and a little noise."""
    base = rng.uniform(110.0, 220.0)
    phase = rng.uniform(0.0, 2 * math.pi)
    out = array.array("h")
    for index in range(int(seconds * rate)):
        t = index / rate
        envelope = 0.55 + 0.45 * math.sin(2 * math.pi * 3.0 * t)
        wave_value = math.sin(2 * math.pi * base * t + phase) + 0.5 * math.sin(2 * math.pi * 2 * base * t)
        value = amplitude * envelope * wave_value / 1.5 + rng.uniform(-60, 60)
        out.append(int(max(-32768, min(32767, value))))
    return out


def write_clip(path: Path, kind: str, seed: int) -> None:
    """Write one clip of a given kind: valid, stereo_48k, silent, clipped, too_short, truncated or not_audio."""
    rng = random.Random(seed)
    if kind == "valid":
        write_wav(path, tone(rng, 1.5))
    elif kind == "stereo_48k":
        mono = tone(rng, 1.5, rate=48000)
        stereo = array.array("h")
        for value in mono:
            stereo.extend((value, value))
        write_wav(path, stereo, rate=48000, channels=2)
    elif kind == "silent":
        write_wav(path, array.array("h", [rng.randint(-4, 4) for _ in range(RATE)]))
    elif kind == "clipped":
        write_wav(path, tone(rng, 1.5, amplitude=90000))
    elif kind == "too_short":
        write_wav(path, tone(rng, 0.2))
    elif kind == "truncated":
        write_wav(path, tone(rng, 1.5))
        data = path.read_bytes()
        path.write_bytes(data[: len(data) // 2])
    elif kind == "not_audio":
        path.write_bytes(b"this is not a RIFF file\n")
    else:
        raise ValueError(f"unknown clip kind {kind!r}")


def consent_record(consent_id: str, speaker_id: str, status: str = "active",
                   permitted_uses: tuple[str, ...] = ("training", "evaluation"),
                   expires_at: str | None = None, revoked_at: str | None = None) -> dict[str, Any]:
    """A consent record for a synthetic speaker; it validates against the consent schema."""
    record: dict[str, Any] = {
        "schema_version": "1.0.0",
        "consent_id": consent_id,
        "subject": {"type": "synthetic", "speaker_id": speaker_id,
                    "description": "Generated tone. No person is recorded."},
        "status": status,
        "granted_at": GRANTED_AT,
        "permitted_uses": list(permitted_uses),
        "license": {"identifier": "MIT"},
        "evidence": {"kind": "not-applicable-synthetic", "reference": "synthetic data generated by the application"},
    }
    if expires_at:
        record["expires_at"] = expires_at
    if revoked_at:
        record["revoked_at"] = revoked_at
    return record


def consent_for(speaker_id: str) -> dict[str, Any]:
    consent_id, mode = SPEAKERS[speaker_id]
    if mode == "revoked":
        return consent_record(consent_id, speaker_id, "revoked", revoked_at="2026-02-01T00:00:00Z")
    if mode == "expired":
        return consent_record(consent_id, speaker_id, "expired", expires_at=PAST)
    if mode == "no_training_use":
        return consent_record(consent_id, speaker_id, permitted_uses=("evaluation", "analytics"), expires_at=FUTURE)
    return consent_record(consent_id, speaker_id, expires_at=FUTURE)


def build_dataset(out_dir: Path, seed: int = 7) -> dict[str, Any]:
    """Write the clips, the consent records and `plan.json` under `out_dir`; return the plan."""
    clips_dir = out_dir / "clips"
    consents_dir = out_dir / "consents"
    clips_dir.mkdir(parents=True, exist_ok=True)
    consents_dir.mkdir(parents=True, exist_ok=True)
    plan: dict[str, Any] = {"seed": seed, "consents": [], "clips": []}
    for speaker_id, (consent_id, _mode) in SPEAKERS.items():
        (consents_dir / f"{consent_id}.json").write_text(json.dumps(consent_for(speaker_id), indent=2) + "\n")
        plan["consents"].append({"consent_id": consent_id, "speaker": speaker_id,
                                 "file": f"consents/{consent_id}.json"})
    for position, (clip_id, (speaker_id, kind, expected)) in enumerate(CLIPS.items()):
        write_clip(clips_dir / f"{clip_id}.wav", kind, seed * 1000 + position)
        plan["clips"].append({"clip_id": clip_id, "file": f"clips/{clip_id}.wav", "speaker": speaker_id,
                              "consent_id": SPEAKERS[speaker_id][0], "kind": kind,
                              "text": TEXTS[position % len(TEXTS)], "expected": expected})
    (out_dir / "plan.json").write_text(json.dumps(plan, indent=2) + "\n")
    return plan
